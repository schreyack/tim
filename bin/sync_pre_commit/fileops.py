"""File locking, unlocking, and git operations."""

from __future__ import annotations

import subprocess
from pathlib import Path

from sync_pre_commit.config import GREEN, NC, RED, YELLOW, BLUE


def unlock_file(path: Path) -> None:
    """Remove immutable flags if present (both system and user)."""
    if not path.exists():
        return
    try:
        subprocess.run(
            ["sudo", "chflags", "noschg", str(path)],
            check=False,
            capture_output=True,
        )
        subprocess.run(
            ["chflags", "nouchg", str(path)],
            check=False,
            capture_output=True,
        )
    except FileNotFoundError:
        pass  # chflags not available (non-macOS)


def lock_file(path: Path) -> None:
    """Set user immutable flag (no sudo needed)."""
    try:
        subprocess.run(
            ["chflags", "uchg", str(path)],
            check=False,
            capture_output=True,
        )
    except FileNotFoundError:
        pass  # chflags not available (non-macOS)


def is_file_locked(path: Path) -> bool:
    """Check if file has the user immutable flag set."""
    if not path.exists():
        return False
    try:
        result = subprocess.run(
            ["stat", "-f", "%f", str(path)],
            capture_output=True,
            text=True,
            check=False,
        )
        if result.returncode == 0:
            flags = int(result.stdout.strip())
            return bool(flags & 0x000002)  # UF_IMMUTABLE
    except (FileNotFoundError, ValueError):
        pass
    return False


def has_autogen_header(path: Path) -> bool:
    """Check if a file has the AUTO-GENERATED header."""
    if not path.exists() or path.is_symlink():
        return False
    try:
        with open(path) as f:
            first_line = f.readline()
            return "AUTO-GENERATED by tim/bin/sync-pre-commit" in first_line
    except OSError:
        return False


def _git(project: Path, *args: str) -> subprocess.CompletedProcess[str]:
    """Run a git command in the project directory."""
    return subprocess.run(
        ["git", "-C", str(project), *args],
        capture_output=True,
        text=True,
        check=False,
    )


def _git_stage_and_commit(project: Path) -> bool | None:
    """Stage and commit .pre-commit-config.yaml. Returns True/False/None (no changes)."""
    name = project.name

    result = _git(project, "add", ".pre-commit-config.yaml")
    if result.returncode != 0:
        print(f"  {RED}✗{NC} {name} - git add failed: {result.stderr.strip()}")
        return False

    result = _git(project, "diff", "--cached", "--quiet")
    if result.returncode == 0:
        print(f"  {BLUE}─{NC} {name} - no changes to commit")
        return None

    result = _git(
        project, "commit",
        "--no-verify", "-m", "chore: sync pre-commit config",
    )
    if result.returncode != 0:
        print(f"  {RED}✗{NC} {name} - commit failed: {result.stderr.strip()}")
        return False
    print(f"  {GREEN}✓{NC} {name} - committed")
    return True


def git_commit_and_push(project: Path, *, push: bool = True) -> bool:
    """Commit and optionally push .pre-commit-config.yaml changes.

    Uses --no-verify because protect-enforcement-files blocks commits
    touching .pre-commit-config.yaml. This is safe - sync-pre-commit
    is a human-invoked trusted tool.
    """
    committed = _git_stage_and_commit(project)
    if committed is False:
        return False
    if not push or committed is None:
        return True

    name = project.name
    result = _git(project, "push")
    if result.returncode != 0:
        print(f"  {RED}✗{NC} {name} - push failed: {result.stderr.strip()}")
        return False
    print(f"  {GREEN}✓{NC} {name} - pushed")
    return True


def print_schg_commands(synced_paths: list[Path]) -> None:
    """Print sudo chflags schg commands for the user to run."""
    if not synced_paths:
        return
    print(f"\n{YELLOW}To apply system-level lock (requires sudo):{NC}")
    for path in synced_paths:
        print(f"  sudo chflags schg {path}")
